import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {join} from 'node:path';
import assert from 'node:assert/strict';
import asar from '@electron/asar';
import yaml from 'js-yaml';
const manifest=JSON.parse(await readFile('package.json','utf8'));
const directory=process.argv[2]||`release/${manifest.version}`;
const metadata=yaml.load(await readFile(join(directory,'latest.yml'),'utf8'));
const config=yaml.load(await readFile(join(directory,'win-unpacked/resources/app-update.yml'),'utf8'));
assert.equal(metadata.version,manifest.version);
assert.deepEqual([config.provider,config.owner,config.repo],['github','DSuzuki35','Sidecast']);
assert.deepEqual(config.publisherName,['Open Source Developer Daniel Sosulski']);
const filename=`Sidecast-${manifest.version}-Setup.exe`;
assert.equal(metadata.files.length,1);assert.equal(metadata.files[0].url,filename);
const installer=await readFile(join(directory,filename));
assert.equal(metadata.files[0].size,installer.length);
assert.equal(metadata.files[0].sha512,createHash('sha512').update(installer).digest('base64'));
const archive=join(directory,'win-unpacked/resources/app.asar');
const files=asar.listPackage(archive);
const privateFiles=files.filter(p=>/\.(wav|mp3|flac|ogg|opus|m4a|aac|mp4|safetensors|pt|pth|ckpt|onnx|npy|npz|pkl|pem|key|pfx|p12)$/i.test(p)||/(^|[/\\])(reference\.json|settings\.json|\.env|recordings|voice|voices|models)([/\\]|$)/i.test(p));
assert.deepEqual(privateFiles,[],'Private data must never be packaged');
const packagedManifest=JSON.parse(asar.extractFile(archive,'package.json'));
for(const key of ['name','version','main','type','dependencies'])assert.deepEqual(packagedManifest[key],manifest[key]);
for(const p of ['src/main.js','src/updates.js','src/preload.cjs','public/app.js','public/index.html'])assert.ok(asar.extractFile(archive,p).equals(await readFile(p)),`Packaged ${p} differs from source`);
const checksums=[];
for(const p of [filename,filename+'.blockmap','latest.yml'])checksums.push(createHash('sha256').update(await readFile(join(directory,p))).digest('hex')+'  '+p);
await writeFile(join(directory,'SHA256SUMS.txt'),checksums.join('\n')+'\n');
console.log(`PASS: ${manifest.version} installer metadata, publisher/feed, packaged source, no private media/models/settings; SHA256SUMS.txt written`);
